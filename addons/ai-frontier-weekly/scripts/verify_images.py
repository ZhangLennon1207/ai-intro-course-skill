#!/usr/bin/env python3
"""验证周报本地图片及可选的线上图片；不发布文件。

python verify_images.py --html weekly-site/index.html
python verify_images.py --html weekly-site/index.html --base https://example.com
可用--sharecode提供本次验证的访问码；不会将其写入Referer、日志或配置。
无图页面返回0并明确说明未验证线上图片；有图时需要可选依赖Pillow。
"""
from __future__ import annotations

import argparse
from html.parser import HTMLParser
import http.cookiejar
import importlib.util
import io
from pathlib import Path
from pathlib import PurePosixPath
import sys
import urllib.parse
import urllib.request


# Both scripts travel together in this Skill. Loading this sibling only defines
# functions; it performs no network or credential operation at import time.
_spec = importlib.util.spec_from_file_location("ai_weekly_image_fetcher", Path(__file__).with_name("fetch_images.py"))
network = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(network)
UA = network.UA


class ReportImages(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.sources = []

    def handle_starttag(self, tag, attrs):
        values = dict(attrs)
        if tag.lower() == "img":
            # This pipeline emits one local src per image. Browser-selected
            # alternatives must not bypass a successful check of only src.
            if values.get("srcset"):
                self.sources.append("")
            self.sources.append(values.get("src") or "")
        elif tag.lower() == "source" and values.get("srcset"):
            self.sources.append("")


def collect_imgs(html):
    parser = ReportImages()
    parser.feed(html)
    return parser.sources


def image_path(source):
    """Only same-bundle relative image URLs; decode escapes before checking."""
    parsed = urllib.parse.urlsplit(source)
    if (not source or parsed.scheme or parsed.netloc or "\\" in source
            or source.startswith("/") or any(c in source for c in "\r\n\x00")):
        raise ValueError("图片必须使用本地相对路径")
    path = urllib.parse.unquote(parsed.path)
    # A second encoded layer is not generated by our pipeline; refuse rather
    # than relying on browser/server-specific multiple decoding behavior.
    if (not path or path.startswith("/") or "\\" in path or ":" in path
            or "\x00" in path or "%" in path or ".." in PurePosixPath(path).parts):
        raise ValueError("图片路径越界或编码不明确")
    return path


def decode_image(blob):
    image_type = network.pillow_image()
    if image_type is None:
        raise ValueError("缺少Pillow配图校验依赖")
    with image_type.open(io.BytesIO(blob)) as image:
        if image.width * image.height > 40_000_000:
            raise ValueError("图片超过40MP")
        image.verify()
    with image_type.open(io.BytesIO(blob)) as image:
        image.load()
        return image.size


def origin(url):
    parsed = urllib.parse.urlsplit(url)
    return parsed.scheme.lower(), parsed.hostname, parsed.port or (443 if parsed.scheme == "https" else 80)


def build_opener(base):
    expected = origin(base)
    def check(url):
        network.public_url(url)
        if origin(url) != expected:
            raise ValueError("线上图片验证不跟随跨站或跨协议跳转")
    cookies = http.cookiejar.CookieJar()
    return urllib.request.build_opener(urllib.request.HTTPCookieProcessor(cookies), network.CheckedRedirect(check))


def fopen(opener, url, referer=None, timeout=25):
    network.public_url(url)
    headers = {"User-Agent": UA, "Accept": "*/*", "Accept-Encoding": "identity"}
    if referer:
        page = urllib.parse.urlsplit(referer)
        headers["Referer"] = urllib.parse.urlunsplit((page.scheme, page.netloc, page.path, "", ""))
    return opener.open(urllib.request.Request(url, headers=headers), timeout=timeout)


def main(argv=None):
    parser = argparse.ArgumentParser(description="周报图片本地及线上自检，不发布文件")
    parser.add_argument("--html", required=True)
    parser.add_argument("--base", default=None)
    parser.add_argument("--sharecode", default=None)
    parser.add_argument("--timeout", type=int, default=25)
    args = parser.parse_args(argv)
    if args.timeout < 1 or args.timeout > 60:
        parser.error("timeout需在1至60秒之间")
    if args.sharecode and not args.base:
        parser.error("sharecode只用于本次--base线上验证")
    page_file = Path(args.html)
    try:
        html = page_file.read_text(encoding="utf-8-sig")
    except (OSError, UnicodeError) as exc:
        print(f"[错误] 无法读取本地HTML({type(exc).__name__})")
        return 1
    sources = collect_imgs(html)
    if not sources:
        print("本期无图：本地图片检查通过；未进行线上页面或图片验证。请在周报页脚说明无图原因。")
        return 0
    if network.pillow_image() is None:
        print("[错误] 有图页面需要可选Pillow依赖；当前不能宣称图片校验通过。")
        return 1
    root = page_file.resolve().parent
    paths, failures = [], []
    for source in sources:
        try:
            relative = image_path(source)
            path = (root / relative).resolve()
            if not path.is_relative_to(root) or not path.is_file():
                raise ValueError("图片缺失或路径越界")
            decode_image(path.read_bytes())
            paths.append(relative)
            print(f"[本地OK] {relative}")
        except Exception as exc:
            # Do not echo the source value; it may be a forbidden credential URL.
            failures.append(type(exc).__name__)
            print(f"[本地失败] 第{len(paths) + len(failures)}张图片({type(exc).__name__})")
    if failures:
        print(f"自检未通过：{len(failures)}项；未请求线上资源。")
        return 1
    if not args.base:
        print(f"本地自检通过：{len(paths)}张图片可解码；未进行线上验证。")
        return 0
    try:
        base = args.base.rstrip("/") + "/"
        parsed = network.public_url(base)
        if parsed.query or parsed.fragment:
            raise ValueError("base不接受查询参数或片段；访问码请用sharecode")
        opener = build_opener(base)
        page_url = base + ("?sharecode=" + urllib.parse.quote(args.sharecode, safe="") if args.sharecode else "")
        with fopen(opener, page_url, timeout=args.timeout) as response:
            if response.status != 200 or origin(response.geturl()) != origin(base):
                raise ValueError("首页未成功或发生跨站跳转")
        for relative in paths:
            # Retain only the decoded path, not a query/fragment from HTML.
            url = urllib.parse.urljoin(base, urllib.parse.quote(relative, safe="/"))
            with fopen(opener, url, referer=base, timeout=args.timeout) as response:
                if (response.status != 200 or origin(response.geturl()) != origin(base)
                        or not response.headers.get("Content-Type", "").lower().startswith("image/")):
                    raise ValueError("线上响应不是同站成功图片")
                blob = response.read(network.MAX_RESPONSE_BYTES + 1)
                if len(blob) > network.MAX_RESPONSE_BYTES:
                    raise ValueError("图片响应过大")
                decode_image(blob)
            print(f"[线上OK] {relative}")
    except Exception as exc:
        print(f"线上自检未通过({type(exc).__name__})；不输出地址查询参数或访问码。")
        return 1
    print(f"自检通过：本地与线上共{len(paths)}张图片均可解码。此结果不验证正文是否已更新。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
